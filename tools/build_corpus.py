def json_dumps(doc):
    import json
    return json.dumps(doc, ensure_ascii=False, indent=2)


def print_stats(quotes, companions, out_dir):
    import json
    from collections import Counter
    src = Counter(q["source"] for q in quotes)
    tags = Counter(q["tag"] for q in quotes)
    lens = [len(q["text"]) for q in quotes]
    dup = len(quotes) - len({q["text"].replace(" ", "") for q in quotes})
    print(f"金句 {len(quotes)} 条 → {out_dir / 'quotes.json'}")
    print(f"伴读 {len(companions)} 条 → {out_dir / 'companion.json'}")
    print(f"文本重复 {dup} · 最长 {max(lens)} 字 · 平均 {sum(lens)/len(lens):.1f} 字")
    print("\n来源分布 TOP15:")
    for k, v in src.most_common(15):
        print(f"  {k:22s} {v}")
    print("\n标签分布:")
    print("  " + "  ".join(f"{k}{v}" for k, v in tags.most_common()))


