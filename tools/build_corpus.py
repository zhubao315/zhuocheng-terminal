def collect_items():
    items, seen = [], set()
    for lst, source, _prio in MODULES:
        for text in lst:
            key = text.replace(" ", "").replace("　", "")
            if key in seen:
                continue
            seen.add(key)
            if source is None:  # 转写条目细分来源
                src = "拙诚日课 · 原创"
                for kws, s in TRANSPOSE_SOURCE:
                    if any(k in text for k in kws):
                        src = s
                        break
                items.append({"text": text, "source": src, "_prio": 3, "_orig": True})
            else:
                items.append({"text": text, "source": source, "_prio": _prio, "_orig": False})
    return items


def trim_to_target(items):
    while len(items) > TARGET:
        # 优先裁剪：转写（尾）→ 原创（尾）→ 任何优先级最低的（尾）
        dropped = False
        for prio in (3, 2, 1):
            idx = next((i for i in range(len(items) - 1, -1, -1) if items[i]["_prio"] == prio), None)
            if idx is not None:
                items.pop(idx)
                dropped = True
                break
        if not dropped:
            break
    return items


def build():
    items = collect_items()
    items = trim_to_target(items)
    if len(items) < TARGET:
        raise SystemExit(f"语料不足：{len(items)} < {TARGET}，请向 corpus_sources/ 补充条目。")

